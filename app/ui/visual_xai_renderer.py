from io import BytesIO
from typing import Optional
import urllib.error
import urllib.request

import streamlit as st


DEFAULT_API_URL = "http://127.0.0.1:8765"


VISUAL_ENDPOINTS = {
    "Grad-CAM": "/visual-xai/gradcam",
    "Grad-CAM++": "/visual-xai/gradcam-plus-plus",
    "Grad-CAM Attention Region": (
        "/visual-xai/gradcam-attention-box"
    ),
    "Grad-CAM++ Attention Region": (
        "/visual-xai/gradcam-plus-plus-attention-box"
    ),
}


def _normalize_api_url(api_url):
    """
    Normalize the API URL while accepting None,
    positional values, and keyword values.
    """

    if api_url is None:
        return DEFAULT_API_URL

    value = str(api_url).strip()

    if not value:
        return DEFAULT_API_URL

    return value.rstrip("/")


def _download_image(url, timeout=30):
    """
    Download one real visual-XAI artifact from the production API.
    """

    request = urllib.request.Request(
        url,
        method="GET",
    )

    try:

        with urllib.request.urlopen(
            request,
            timeout=timeout,
        ) as response:

            status = response.status
            content_type = response.headers.get(
                "Content-Type",
                "",
            )

            body = response.read()

            return (
                status,
                content_type,
                body,
                None,
            )

    except urllib.error.HTTPError as exc:

        try:
            body = exc.read()
        except Exception:
            body = b""

        return (
            exc.code,
            "",
            body,
            str(exc),
        )

    except Exception as exc:

        return (
            None,
            "",
            b"",
            str(exc),
        )


def _render_one_image(
    title,
    endpoint,
    api_url,
):
    """
    Render one visual-XAI image returned by the API.
    """

    st.subheader(title)

    url = (
        _normalize_api_url(api_url)
        + endpoint
    )

    status, content_type, body, error = (
        _download_image(url)
    )

    if status != 200:

        st.error(
            "Visual XAI image request failed: "
            + str(error or status)
        )

        return False

    if not body:

        st.error(
            "Visual XAI endpoint returned an empty image."
        )

        return False

    # The API is expected to return PNG/JPEG image bytes.
    is_image = (
        "image/" in content_type.lower()
        or body.startswith(b"\x89PNG")
        or body.startswith(b"\xff\xd8")
    )

    if not is_image:

        st.error(
            "Visual XAI endpoint did not return image data."
        )

        return False

    try:

        st.image(
            BytesIO(body),
            caption=title,
            use_container_width=True,
        )

        st.caption(
            "Source: production Visual XAI API"
        )

        return True

    except TypeError:

        # Compatibility with Streamlit versions where
        # use_container_width may differ.
        st.image(
            BytesIO(body),
            caption=title,
        )

        st.caption(
            "Source: production Visual XAI API"
        )

        return True


def display_visual_xai(
    api_url: Optional[str] = None,
    *args,
    **kwargs,
):
    """
    Production Streamlit Visual XAI renderer.

    Compatible with:
        display_visual_xai()
        display_visual_xai(api_url)
        display_visual_xai(api_url=...)

    The function displays actual PNG/JPEG visual artifacts
    from the validated production API.
    """

    # Compatibility:
    # If an older caller supplies the API URL through kwargs,
    # accept it without raising an unexpected-keyword error.
    if api_url is None:

        candidate = kwargs.get(
            "api_url"
        )

        if candidate:
            api_url = candidate

    api_url = _normalize_api_url(
        api_url
    )

    st.markdown(
        "### Visual XAI"
    )

    st.caption(
        "Visual explanations generated by the production "
        "Grad-CAM / Grad-CAM++ API."
    )

    results = {}

    for title, endpoint in VISUAL_ENDPOINTS.items():

        results[title] = _render_one_image(
            title,
            endpoint,
            api_url,
        )

    successful = sum(
        1
        for value in results.values()
        if value
    )

    if successful == len(
        VISUAL_ENDPOINTS
    ):

        st.success(
            "All production Visual XAI images loaded successfully."
        )

    elif successful > 0:

        st.warning(
            f"{successful}/{len(VISUAL_ENDPOINTS)} "
            "Visual XAI images loaded."
        )

    else:

        st.error(
            "No Visual XAI images could be loaded."
        )

    st.caption(
        "Attention boxes indicate MODEL ATTENTION REGION, "
        "not medically validated lesion boundaries."
    )

    return results
